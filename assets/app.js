function renderGallery(images, titlePrefix) {
  const gallery = document.createElement("div");
  gallery.className = "gallery";
  images.forEach((imgPath, idx) => {
    const fig = document.createElement("figure");
    const caption = `${titlePrefix} · 截图 ${idx + 1} · ${fileName(imgPath)}`;
    fig.innerHTML = `
      <img src="${imageUrl(imgPath)}" alt="${caption}" data-caption="${caption}">
      <figcaption title="${fileName(imgPath)}">${fileName(imgPath)}</figcaption>
    `;
    gallery.appendChild(fig);
  });
  return gallery;
}

function renderSystems() {
  const container = document.getElementById("systemsContainer");

  systemsData.forEach((system) => {
    const cfg = copyMap[system.title] || { desc: "系统介绍待补充。", features: [] };
    const article = document.createElement("article");
    article.className = "system-section";
    article.id = getSectionId(system);

    article.innerHTML = `
      <div class="section-head">
        <div>
          <div class="section-title">
            <h3>${system.title}</h3>
            <span class="badge">${getAllImageCount(system)} 张截图</span>
          </div>
          <p class="description">${cfg.desc}</p>
        </div>
      </div>
    `;

    const primaryImage = getPrimaryImage(system);
    if (primaryImage) {
      const keyShot = document.createElement("figure");
      keyShot.className = "key-shot";
      keyShot.innerHTML = `
        <img src="${imageUrl(primaryImage)}" alt="${system.title} 关键主图" data-caption="${system.title} · 关键主图">
        <p>关键主图（汇报模式展示）</p>
      `;
      article.appendChild(keyShot);
    }

    article.appendChild(renderFeatureList(cfg.features));

    if (system.images.length > 0) {
      article.appendChild(renderGallery(system.images, system.title));
    }

    if (system.modules.length > 0) {
      system.modules.forEach((mod) => {
        const modCfg = copyMap[mod.title] || { desc: "子模块介绍待补充。", features: [] };
        const block = document.createElement("section");
        block.className = "module-block";
        block.innerHTML = `
          <h4>${mod.title}</h4>
          <p class="description">${modCfg.desc}</p>
        `;
        block.appendChild(renderFeatureList(modCfg.features));
        block.appendChild(renderGallery(mod.images, `${system.title} / ${mod.title}`));
        article.appendChild(block);
      });
    }

    container.appendChild(article);
  });
}

function bindLightbox() {
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  const lightboxCaption = document.getElementById("lightboxCaption");
  const closeBtn = document.getElementById("lightboxClose");

  document.body.addEventListener("click", (event) => {
    const target = event.target;
    if (!(target instanceof HTMLImageElement)) return;
    if (!target.closest(".gallery")) return;
    lightboxImg.src = target.src;
    lightboxCaption.textContent = target.dataset.caption || target.alt || "";
    lightbox.classList.remove("hidden");
    lightbox.setAttribute("aria-hidden", "false");
  });

  const close = () => {
    lightbox.classList.add("hidden");
    lightbox.setAttribute("aria-hidden", "true");
    lightboxImg.src = "";
  };

  closeBtn.addEventListener("click", close);
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) close();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") close();
  });
}

function bindBackToTop() {
  const btn = document.getElementById("backToTop");
  window.addEventListener("scroll", () => {
    if (window.scrollY > 320) btn.classList.add("show");
    else btn.classList.remove("show");
  });
  btn.addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));
}

function bindNavActive() {
  const sections = [
    ...["value", "overview", "relation", "timeline", "systems"]
      .map((id) => document.getElementById(id))
      .filter(Boolean),
    ...document.querySelectorAll(".system-section")
  ];
  const links = [...document.querySelectorAll(".top-nav a")];
  const sectionById = new Map(sections.map((sec) => [sec.id, sec]));

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        links.forEach((l) => l.classList.remove("active"));
        const id = entry.target.id;
        const active = links.find((l) => l.getAttribute("href") === `#${id}`);
        if (active) active.classList.add("active");
      });
    },
    { rootMargin: "-30% 0px -55% 0px", threshold: 0.1 }
  );

  sectionById.forEach((sec) => observer.observe(sec));
}

function bindMobileNav() {
  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("topNav");
  toggle.addEventListener("click", () => nav.classList.toggle("open"));
  nav.addEventListener("click", (event) => {
    const target = event.target;
    if (target instanceof HTMLAnchorElement) nav.classList.remove("open");
  });
}

function bindReportMode() {
  const key = "project_intro_report_mode";
  const btn = document.getElementById("reportModeToggle");
  if (!btn) return;

  const applyMode = (isOn) => {
    document.body.classList.toggle("report-mode", isOn);
    btn.classList.toggle("is-on", isOn);
    btn.textContent = `领导汇报模式：${isOn ? "开" : "关"}`;
    btn.setAttribute("aria-pressed", String(isOn));
  };

  const cached = window.localStorage.getItem(key) === "1";
  applyMode(cached);

  btn.addEventListener("click", () => {
    const nowOn = !document.body.classList.contains("report-mode");
    applyMode(nowOn);
    window.localStorage.setItem(key, nowOn ? "1" : "0");
  });
}

function bootstrap() {
  renderNav();
  renderValue();
  renderOverview();
  renderRelation();
  renderTimeline();
  renderSystems();
  bindLightbox();
  bindBackToTop();
  bindNavActive();
  bindMobileNav();
  bindReportMode();
}

